#!/usr/bin/env python3
"""Render or check TLA+ machine modules from std::machine to_json() stream on stdin."""

import json
import os
import sys


def read_json_stream(raw):
    dec = json.JSONDecoder()
    tables = []
    idx = 0
    n = len(raw)
    while idx < n:
        while idx < n and raw[idx].isspace():
            idx += 1
        if idx >= n:
            break
        obj, idx = dec.raw_decode(raw, idx)
        tables.append(obj)
    return tables


def tla_str(val):
    return '"' + val.replace("\\", "\\\\").replace('"', '\\"') + '"'


def tla_set(items):
    return "{" + ", ".join(tla_str(x) for x in items) + "}"


def render_module(name, table):
    states = table["states"]
    events = table["events"]
    outcomes = table["outcomes"]
    start = table["start"]
    moves = table["moves"]

    expected_pairs = len(states) * len(events)
    if len(moves) != expected_pairs:
        raise ValueError(f"{name}: expected {expected_pairs} total moves, got {len(moves)}")

    lines = [
        "\\* GENERATED by scripts/machine-tla.py from std::machine to_json(). Do not edit.",
        f"---- MODULE {name} ----",
        f"States == {tla_set(states)}",
        f"Events == {tla_set(events)}",
        f"Outcomes == {tla_set(outcomes)}",
        f"Start == {tla_str(start)}",
        "",
        "Move(s, e) ==",
    ]
    for i, mv in enumerate(moves):
        prefix = "    CASE " if i == 0 else "      [] "
        lines.append(
            f"{prefix}s = {tla_str(mv['from'])} /\\ e = {tla_str(mv['event'])}"
            f" -> <<{tla_str(mv['to'])}, {tla_str(mv['outcome'])}>>"
        )
    lines.extend([
        "",
        "VARIABLES state, previous, event, outcome, moved",
        "",
        "vars == <<state, previous, event, outcome, moved>>",
        "",
        "TypeOK ==",
        "    /\\ state \\in States",
        "    /\\ previous \\in States",
        "    /\\ event \\in Events",
        "    /\\ outcome \\in Outcomes",
        "    /\\ moved \\in BOOLEAN",
        "",
        "Init ==",
        "    /\\ state = Start",
        "    /\\ previous = Start",
        "    /\\ event \\in Events",
        "    /\\ outcome \\in Outcomes",
        "    /\\ moved = FALSE",
        "",
        "Take(e) ==",
        "    /\\ state' = Move(state, e)[1]",
        "    /\\ previous' = state",
        "    /\\ event' = e",
        "    /\\ outcome' = Move(state, e)[2]",
        "    /\\ moved' = TRUE",
        "",
        "Next == \\E e \\in Events : Take(e)",
        "",
        "Spec == Init /\\ [][Next]_vars",
        "====",
        "",
    ])
    return "\n".join(lines)


def main():
    args = sys.argv[1:]
    check = False
    if args and args[0] == "--check":
        check = True
        args = args[1:]
    if not args:
        sys.stderr.write("usage: machine-tla.py [--check] <module.tla>...\n")
        return 2

    tables = read_json_stream(sys.stdin.read())
    if len(tables) != len(args):
        sys.stderr.write(f"machine-tla: {len(args)} files for {len(tables)} tables\n")
        return 1

    stale = False
    for path, table in zip(args, tables):
        mod_name = os.path.splitext(os.path.basename(path))[0]
        rendered = render_module(mod_name, table)
        if check:
            if not os.path.isfile(path):
                sys.stderr.write(f"machine-tla: {path} is missing; run `sh scripts/spec-gen.sh`\n")
                stale = True
                continue
            with open(path, "r", encoding="utf-8") as f:
                existing = f.read()
            if existing != rendered:
                sys.stderr.write(f"machine-tla: {path} is out of step with std::machine; run `sh scripts/spec-gen.sh`\n")
                stale = True
        else:
            os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
            with open(path, "w", encoding="utf-8") as f:
                f.write(rendered)

    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
